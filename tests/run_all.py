def run_all_tests():
    """Run all tests and report results."""
    print()
    print("=" * 70)
    print("OTA Integration Tests")
    print("=" * 70)
    
    # Load config
    config = OTATestConfig()
    print()
    print(config)
    print()
    
    # Validate prerequisites
    errors = config.validate()
    if errors:
        print("✗ PREREQUISITES FAILED:")
        for error in errors:
            print(f"  • {error}")
        print()
        return False
    
    print("✓ All prerequisites met")
    print()
    
    # Load firmware metadata
    try:
        metadata = load_firmware_metadata(config)
    except Exception as e:
        print(f"✗ Cannot load firmware metadata: {e}")
        return False
    
    # Run tests
    results = [
        test_ota_firmware_download(config, metadata),
        test_ota_invalid_token_rejected(config, metadata),
        test_ota_missing_device_id_rejected(config, metadata),
    ]
    
    # Report results
    print()
    for result in results:
        print(result.format_result())
        if result.details:
            for key, value in result.details.items():
                print(f"    {key}: {value}")
    
    print()
    passed = sum(1 for r in results if r.passed)
    failed = sum(1 for r in results if not r.passed)
    
    print(f"Tests: {passed} passed, {failed} failed")
    print()
    
    return failed == 0


if __name__ == "__main__":
    success = run_all_tests()
    sys.exit(0 if success else 1)

