"""
OTA Integration Tests - Run inside OTA add-on container

Tests the existing OTA firmware download against a running OTA server.
No mocking - real HTTPS communication with real firmware.

This test runner is designed to be run INSIDE the Home Assistant OTA add-on container,
where /data/ota_token_secret.bin and the running OTA server are available.
"""

